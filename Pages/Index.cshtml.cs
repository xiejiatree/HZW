    private readonly ILogger<IndexModel> _logger;
     private readonly SnowflakeService _snowflake;

    public IndexModel(ILogger<IndexModel> logger, SnowflakeService snowflake)
    {
        _logger = logger;
        _snowflake = snowflake; 
    }

    //  [IgnoreAntiforgeryToken]
    public async Task<IActionResult> OnGetSentenceAsync(
    string vocab,
    string? modelName,
    string? complexity)
{
    if (string.IsNullOrWhiteSpace(vocab))
    {
        return new JsonResult(new { sentence = string.Empty });
    }

    var effectiveComplexity = string.IsNullOrWhiteSpace(complexity)
        ? "simple"
        : complexity.Trim().ToLowerInvariant();

    try
    {
        _logger.LogInformation(
            "Generating sentence for vocab {Vocab} with model {ModelName} and complexity {Complexity}",
            vocab,
            modelName,
            effectiveComplexity
        );

        var sentence = await _snowflake.GenerateSentenceAsync(vocab, effectiveComplexity);
        return new JsonResult(new { sentence });
    }
    catch (Exception ex)
    {
        _logger.LogError(ex,
            "Error generating sentence for vocab {Vocab} (model {ModelName}, complexity {Complexity})",
            vocab,
            modelName,
            effectiveComplexity);

        return new JsonResult(new { sentence = string.Empty });
    }
}


